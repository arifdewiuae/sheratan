/** Each file as its path over its source. */
function filesHtml(example: ExampleFiles): string {
  const figures = Object.entries(example).map(
    ([path, source]) =>
      `      <figure><figcaption>${escapeHtml(path)}</figcaption><pre><code>${escapeHtml(source.trimEnd())}</code></pre></figure>`,
  );

  return `    <div class="files">\n${figures.join('\n')}\n    </div>`;
}

/** Where a code is caught and how loudly, in the words the page uses. */
function kindOf(entry: Explanation): string {
  const where =
    entry.caughtBy === CaughtBy.Checker ? 'caught by sheratan check' : 'thrown at run time';

  return `${entry.severity} · ${where}`;
}

/** What happens to the wrong example, and to the right one. */
function outcomes(entry: Explanation): { readonly wrong: string; readonly right: string } {
  if (entry.caughtBy === CaughtBy.Checker) {
    return { wrong: `<code>sheratan check</code> reports ${entry.code}.`, right: 'Checks clean.' };
  }

  return { wrong: `Throws ${entry.code}.`, right: 'Runs without it.' };
}

/** One code's page: what it is, why, code that is caught beside code that is not. */
export function pageFor(entry: Explanation): string {
  const outcome = outcomes(entry);

  const body = `    <header>
      <p class="label">${escapeHtml(kindOf(entry))}</p>
      <h1><span class="code">${entry.code}</span>${prose(entry.title)}</h1>
      <p class="lead">${prose(entry.why)}</p>
    </header>
    <section aria-labelledby="wrong">
      <h2 id="wrong">Wrong</h2>
      <p class="caption">${outcome.wrong}</p>
${filesHtml(entry.wrong)}
    </section>
    <section aria-labelledby="right">
      <h2 id="right">Right</h2>
      <p class="caption">${outcome.right}</p>
${filesHtml(entry.right)}
    </section>
    <section aria-labelledby="terminal">
      <h2 id="terminal">In your terminal</h2>
      <pre class="ask"><code>sheratan explain ${entry.code}          # this page
sheratan explain ${entry.code} --json   # the same, for an agent</code></pre>
    </section>`;

  return shell(
    {
      title: `${entry.code}: ${entry.title.replaceAll('`', '')} · Sheratan`,
      description: entry.why,
      canonical: `${INDEX_URL}${entry.code}/`,
    },
    body,
  );
}

/** One row of the index table. */
function row(entry: Explanation): string {
  return `        <tr><td class="code"><a href="${pathFor(entry.code)}">${entry.code}</a></td><td>${prose(entry.title)}</td><td class="muted hide-narrow">${escapeHtml(kindOf(entry))}</td></tr>`;
}

/** Every code on one page, for a reader who has a symptom and not a code. */
export function indexPage(all: readonly Explanation[], reserved: readonly string[]): string {
  const body = `    <header>
      <p class="label">Error index</p>
      <h1>Every error Sheratan reports, and how to fix it</h1>
      <p class="lead">Each page shows code that triggers the error beside code that doesn't. The examples are run by the test suite, so none of them can go out of date.</p>
    </header>
    <section aria-labelledby="codes">
      <h2 id="codes">${all.length} codes</h2>
      <table>
        <thead><tr><th scope="col">Code</th><th scope="col">What it means</th><th scope="col" class="hide-narrow">Kind</th></tr></thead>
        <tbody>
${all.map(row).join('\n')}
        </tbody>
      </table>
    </section>
    <section aria-labelledby="reserved">
      <h2 id="reserved">Numbered, not checked yet</h2>
      <p class="caption">${reserved.map((code) => `<code>${escapeHtml(code)}</code>`).join(', ')}: reserved by the spec, and given a page in the release that starts checking them.</p>
    </section>`;

  return shell(
    {
      title: 'Error index · Sheratan',
      description:
        'Every error the Sheratan runtime throws and its checker reports, each with code that triggers it beside code that does not.',
      canonical: INDEX_URL,
    },
    body,
  );
}

/** The sitemap entries this generator owns: the index, then each code. */
export function sitemapSection(all: readonly Explanation[]): string {
  const urls = [INDEX_URL, ...all.map((entry) => `${INDEX_URL}${entry.code}/`)];

  return urls.map((url) => `  <url>\n    <loc>${url}</loc>\n  </url>`).join('\n');
}

/** `sitemap` with its generated part replaced by `section`. Throws if the markers are missing. */
export function withSitemapSection(sitemap: string, section: string): string {
  const start = sitemap.indexOf(SITEMAP_START);
  const end = sitemap.indexOf(SITEMAP_END);

  if (start === -1 || end < start) {
    throw new Error(
      `site/sitemap.xml needs the lines ${SITEMAP_START} and ${SITEMAP_END} around the generated entries.`,
    );
  }

  return `${sitemap.slice(0, start + SITEMAP_START.length)}\n${section}\n  ${sitemap.slice(end)}`;
}

/** Why the files on disk differ from what would be generated: missing, stale or orphaned, by path. */
export function staleness(
  expected: ReadonlyMap<string, string>,
  actual: ReadonlyMap<string, string>,
): readonly string[] {
  const problems: string[] = [];

  for (const [path, content] of expected) {
    const found = actual.get(path);

    if (found === undefined) problems.push(`${path} is missing`);
    else if (found !== content) problems.push(`${path} is stale`);
  }

  for (const path of actual.keys()) {
    if (!expected.has(path)) problems.push(`${path} is not generated from any code; remove it`);
  }

  return problems.toSorted();
}
