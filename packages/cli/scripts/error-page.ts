// The error index on sheratan.dev (SPEC §8, §10): one page per code that the
// runtime throws or the checker reports, and a page listing them all. Built
// from the same table `sheratan explain` prints, so the page an error links to
// and the answer the command gives cannot disagree, and every example on it is
// one `test/explain.test.ts` has executed. Pure functions only; `errors.ts`
// owns the file system.

import { DOCS_BASE_URL } from '../../core/src/codes.ts';
