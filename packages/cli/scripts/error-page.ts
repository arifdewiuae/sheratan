/** Where the index lives on the site, and the prefix every code's page sits under. */
export const ERRORS_PATH = '/errors/';

/** Brackets the part of `site/sitemap.xml` this generator owns. */
export const SITEMAP_START = '<!-- generated by packages/cli/scripts/errors.ts -->';

/** Ends the generated part of the sitemap. */
export const SITEMAP_END = '<!-- end generated -->';

/** The index's canonical address: the base every error URL is built on. */
const INDEX_URL = DOCS_BASE_URL;

const ESCAPES: Readonly<Record<string, string>> = {
  '&': '&amp;',
  '<': '&lt;',
  '>': '&gt;',
  '"': '&quot;',
  "'": '&#39;',
};

/** Text made safe to place anywhere in HTML, attribute values included. */
export function escapeHtml(text: string): string {
  return text.replaceAll(/[&<>"']/g, (char) => ESCAPES[char] ?? char);
}

/** A sentence from the table, where `backticks` mark code, as HTML. */
export function prose(text: string): string {
  return text
    .split('`')
    .map((part, index) => (index % 2 === 0 ? escapeHtml(part) : `<code>${escapeHtml(part)}</code>`))
    .join('');
}

/** A page's address on the site. A trailing slash, because each page is a directory. */
export function pathFor(code: string): string {
  return `${ERRORS_PATH}${code}/`;
}

